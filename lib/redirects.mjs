/**
 * Does this path already 301 somewhere?
 *
 * Used by the XML sitemaps (lib/sitemap-sources.js) to drop any URL that
 * redirects, so the sitemap can only ever contain canonical 200 URLs. Yoast's
 * sitemap got this wrong in both directions: it listed two WordPress pages that
 * now 301, and two blog posts whose rewritten versions live at new slugs while
 * the old posts are still published in WordPress.
 *
 * Compiled once at module load. Next's own matcher is the authority at request
 * time; this only has to agree with it on the shapes used in the list above —
 * a literal path, or a trailing ":name*" / ":name" segment.
 */
const EXACT_SOURCES = new Set(REDIRECTS.map(([from]) => from.split("?")[0]).filter((f) => !f.includes(":")));

const WILDCARD_SOURCES = REDIRECTS.map(([from]) => from.split("?")[0])
  .filter((f) => f.includes(":"))
  .map((from) => {
    let pattern = "^";
    for (const part of from.split(/(\/:[a-zA-Z]+\*?)/).filter(Boolean)) {
      const param = part.match(/^\/:([a-zA-Z]+)(\*?)$/);
      if (param) pattern += param[2] ? "(?:\\/.*?)?" : "\\/[^/]+";
      else pattern += part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    }
    return new RegExp(`${pattern}$`);
  });

export function isRedirectSource(pathname) {
  const path = pathname.endsWith("/") ? pathname : `${pathname}/`;
  if (EXACT_SOURCES.has(path) || EXACT_SOURCES.has(path.slice(0, -1))) return true;
  return WILDCARD_SOURCES.some((re) => re.test(path));
}
